def claim_status(row, aud):
    a = aud[(aud.notebook == row["notebook"]) & (aud.cell == row["cell"])].iloc[0]
    if row["notebook"] == "eda" and row["cell"] == 49:
        return "NOT SUPPORTED: chart built from hand-typed RMSE values that differ from computed outputs"
    if row["notebook"] == "eda" and row["cell"] == 50:
        return "SUPERSEDED: saved output is a price-LEVEL fit on a different split; not return-prediction skill"
    if row["notebook"] == "eda":
        return "HISTORICAL: saved output from an earlier experiment (different protocol); not re-executed"
    if a.saved_error:
        return f"UNVERIFIED: supporting cell has a saved error ({a.saved_error})"
    if not a.has_saved_output:
        return "UNVERIFIED: narrative only - supporting cell has no saved output"
    return "HISTORICAL: saved output present; not re-executed in this repository"


