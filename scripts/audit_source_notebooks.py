def cells(path):
    nb = json.loads(Path(path).read_text())
    heading = ""
    for i, c in enumerate(nb["cells"]):
        src = "".join(c["source"])
        if c["cell_type"] == "markdown":
            for line in src.splitlines():
                if line.startswith("#"):
                    heading = line.lstrip("#").strip()
                    break
        yield i, c, src, heading


def audit(path, name):
    rows = []
    for i, c, src, heading in cells(path):
        if c["cell_type"] != "code":
            continue
        outs = c.get("outputs", [])
        err = [o for o in outs if o.get("output_type") == "error"]
        rows.append({"notebook": name, "cell": i, "section": heading, "execution_count": c.get("execution_count"),
                     "first_line": src.strip().splitlines()[0][:90] if src.strip() else "",
                     "n_outputs": len(outs), "has_saved_output": bool(outs) and not err,
                     "saved_error": f"{err[0]['ename']}: {err[0]['evalue']}" if err else ""})
    return pd.DataFrame(rows)


def text_output(path, cell):
    nb = json.loads(Path(path).read_text())
    parts = []
    for o in nb["cells"][cell].get("outputs", []):
        if o.get("output_type") == "stream":
            parts.append("".join(o["text"]))
        elif "data" in o and "text/plain" in o["data"]:
            parts.append("".join(o["data"]["text/plain"]))
    return parts


def parse_forecast_r2(path, cell=38):
    """Parse the R2 column of the two saved section-5.1 tables (price first, then spread)."""
    tables = [p for p in text_output(path, cell) if p.lstrip().startswith("MAE") or "MAE" in p.splitlines()[0]]
    out = []
    for target, txt in zip(["price", "spread"], tables):
        header = txt.splitlines()[0].split()
        assert header[:3] == ["MAE", "RMSE", "R2"], header
        for line in txt.splitlines()[1:]:
            if not line.strip():
                break                       # pandas wraps wide tables; only the first block has R2
            m = re.match(r"^(zero|stock mean|persistence|ridge|HGB|selected)\s+(-?[\d.]+)\s+(-?[\d.]+)\s+(-?[\d.]+)", line)
            if m:
                out.append({"target": target, "model": m.group(1), "MAE": float(m.group(2)),
                            "RMSE": float(m.group(3)), "R2": float(m.group(4)),
                            "source": f"archive/Optiver_Team_Merged.ipynb cell {cell} (saved output)"})
    return pd.DataFrame(out)


