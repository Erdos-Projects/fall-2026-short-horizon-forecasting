"""Command-line runner: ``python -m obforecast.run --config configs/default.yaml``.

Writes metrics (CSV/JSON) to ``<output_dir>/metrics``, figures to ``<output_dir>/figures``, split
identifiers to ``<output_dir>/splits`` and a run manifest with versions, runtimes and the status of
every stage. A stage that fails is recorded as failed (with the error) and later stages that need
its outputs are skipped; nothing is reported as executed unless it ran.

The legacy benchmark windows are scored only with ``--score-benchmark``.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import platform
import subprocess
import sys
import traceback
from pathlib import Path
from time import perf_counter

import numpy as np
import pandas as pd

from . import __version__
from .book import KEYS, build_tables
from .checks import run_checks
from .config import Timing, config_hash, load_config
from .data import ParquetSource, check_layout, resolve_data_dir, select_stocks
from .extra import extra_stock, path_points
from .features import feature_inventory
from . import figures, pipeline
from .validation import fold_table

STAGES = ["features", "checks", "cv", "trading", "sensitivity", "why_spread", "ablation", "stress",
          "leakage", "upgraded", "benchmark"]


def _versions() -> dict:
    out = {"python": sys.version.split()[0], "platform": platform.platform(), "obforecast": __version__}
    for m in ["numpy", "pandas", "sklearn", "scipy", "matplotlib", "pyarrow", "lightgbm", "yaml"]:
        try:
            out[m] = __import__(m).__version__
        except Exception:
            out[m] = "not installed"
    try:
        out["git_commit"] = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True,
                                           check=True).stdout.strip()
    except Exception:
        out["git_commit"] = "unknown"
    return out


class Runner:
    def __init__(self, cfg, out_dir: Path, label: str):
        self.cfg, self.label = cfg, label
        self.metrics, self.figs, self.splits = out_dir / "metrics", out_dir / "figures", out_dir / "splits"
        for p in (self.metrics, self.figs, self.splits):
            p.mkdir(parents=True, exist_ok=True)
        self.out_dir = out_dir
        self.manifest = {"label": label, "config": {k: v for k, v in cfg.items() if not k.startswith("_")},
                         "config_source": cfg.get("_source"), "config_hash": config_hash(cfg),
                         "versions": _versions(), "started": dt.datetime.now().isoformat(timespec="seconds"),
                         "stages": {}}

    def csv(self, df: pd.DataFrame, name: str):
        df.to_csv(self.metrics / f"{name}.csv", index=False)

    def json(self, obj, name: str):
        (self.metrics / f"{name}.json").write_text(json.dumps(obj, indent=2, default=str))

    def stage(self, name, fn, *needs):
        if any(self.manifest["stages"].get(n, {}).get("status") != "executed" for n in needs):
            self.manifest["stages"][name] = {"status": "skipped", "reason": f"requires {needs}"}
            print(f"[{name}] skipped: requires {needs}")
            return None
        t0 = perf_counter()
        print(f"[{name}] running")
        try:
            out = fn()
            self.manifest["stages"][name] = {"status": "executed", "minutes": round((perf_counter() - t0) / 60, 2)}
            return out
        except Exception as e:  # recorded, never hidden
            self.manifest["stages"][name] = {"status": "failed", "error": f"{type(e).__name__}: {e}",
                                             "traceback": traceback.format_exc()[-2000:],
                                             "minutes": round((perf_counter() - t0) / 60, 2)}
            print(f"[{name}] FAILED: {type(e).__name__}: {e}")
            return None

    def skip(self, name, reason):
        self.manifest["stages"][name] = {"status": "skipped", "reason": reason}
        print(f"[{name}] skipped: {reason}")

    def finish(self):
        self.manifest["finished"] = dt.datetime.now().isoformat(timespec="seconds")
        (self.out_dir / "run_manifest.json").write_text(json.dumps(self.manifest, indent=2, default=str))
        if self.label != "full":
            (self.out_dir / "README.md").write_text(
                f"# {self.label.upper()} RUN - not research results\n\nGenerated by `python -m obforecast.run` "
                f"with label `{self.label}` ({self.manifest['started']}). See run_manifest.json.\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="configs/default.yaml")
    ap.add_argument("--data-dir", default=None, help="Kaggle data folder (else $OBF_DATA_DIR, else config)")
    ap.add_argument("--output-dir", default=None, help="override run.output_dir")
    ap.add_argument("--stages", default="all", help=f"comma list of {STAGES} or 'all'")
    ap.add_argument("--score-benchmark", action="store_true",
                    help="score the legacy benchmark windows once (section 9 / 9.1)")
    ap.add_argument("--skip-upgraded", action="store_true", help="skip LightGBM sections 5.2/5.3/9.1")
    ap.add_argument("--synthetic", action="store_true",
                    help="use generated books instead of real data (pipeline test only; label 'synthetic')")
    args = ap.parse_args(argv)

    cfg = load_config(args.config)
    timing = Timing.from_config(cfg)
    label = "synthetic" if args.synthetic else cfg["run"]["label"]
    out_dir = Path(args.output_dir or ("results/synthetic" if args.synthetic else cfg["run"]["output_dir"]))
    stages = STAGES if args.stages == "all" else [s.strip() for s in args.stages.split(",")]
    R = Runner(cfg, out_dir, label)
    cache = Path(cfg["run"]["cache_dir"]) / ("synthetic" if args.synthetic else "")
    cache.mkdir(parents=True, exist_ok=True)

    # ---------------------------------------------------------------- data
    if args.synthetic:
        from .synthetic import make_synthetic
        source, stock_ids = make_synthetic(n_stocks=10, n_windows=120, seed=0)
        R.manifest["data"] = {"source": "synthetic (obforecast.synthetic.make_synthetic)", "stocks": stock_ids}
    else:
        data_dir = resolve_data_dir(args.data_dir, cfg)
        layout = check_layout(data_dir)
        R.manifest["data"] = {"dir": str(data_dir), **{k: v for k, v in layout.items() if k != "book_stocks"}}
        stock_ids = select_stocks(layout["book_stocks"], cfg["run"]["stocks"])
        source = ParquetSource(data_dir)
    R.manifest["data"]["stocks_used"] = len(stock_ids)

    def build():
        f_path, x_path = cache / "tables.pkl", cache / "extra.pkl"
        key = {"stocks": stock_ids, "timing": cfg["timing"]}
        if f_path.exists() and pd.read_pickle(f_path).get("key") == key:
            tabs = pd.read_pickle(f_path)
        else:
            feats, outs, qual, invalid = build_tables(source, stock_ids, timing)
            tabs = {"key": key, "feats": feats, "outs": outs, "quality": qual, "invalid": invalid}
            pd.to_pickle(tabs, f_path)
        extra = None
        if "upgraded" in stages and not args.skip_upgraded:
            if x_path.exists() and pd.read_pickle(x_path).get("key") == key:
                extra = pd.read_pickle(x_path)["extra"]
            else:
                extra = pd.concat([extra_stock(s, source.load("book", s), source.load("trade", s), timing)
                                   for s in stock_ids], ignore_index=True)
                pd.to_pickle({"key": key, "extra": extra}, x_path)
        q = tabs["quality"]
        R.json({"stocks": int(tabs["feats"].stock_id.nunique()), "windows": int(tabs["feats"].time_id.nunique()),
                "eligible rows": int(len(tabs["feats"])), "quality rows": int(len(q)),
                "windows excluded (no valid quote before cut)": int(q.no_initial_state.sum()),
                "invalid snapshots dropped": int(tabs["invalid"].drop(columns="stock_id").to_numpy().sum())
                if tabs["invalid"].shape[1] > 1 else 0,
                "entry ask older than stale threshold": float((q.age_entry > timing.stale_quote_seconds).mean()),
                "exit bid older than stale threshold": float((q.age_exit > timing.stale_quote_seconds).mean())},
               "data_summary")
        return tabs, extra

    built = R.stage("features", build)
    if built is None:
        R.finish(); return 1
    tabs, extra = built
    feats, outs = tabs["feats"], tabs["outs"]
    R.csv(feature_inventory(), "feature_inventory")

    d = pipeline.prepare(feats, outs, cfg, split_path=R.splits / "benchmark_time_ids.csv")
    R.manifest["split"] = d.split_info
    R.csv(fold_table(d.dev_f, cfg), "../splits/development_folds")
    figures.design_figure(R.figs / "study_design.png", timing, cfg["split"]["outer_folds"], cfg["split"]["inner_folds"])

    if "checks" in stages:
        def checks():
            sid = stock_ids[0]
            tab = run_checks(feats, outs, d.dev_f, cfg, timing,
                             sample_stock=(sid, source.load("book", sid), source.load("trade", sid)))
            R.csv(tab, "correctness_checks")
            if not tab.passed.all():
                raise AssertionError(f"failed checks: {list(tab.check[~tab.passed])}")
            return tab
        R.stage("checks", checks)

    cv = R.stage("cv", lambda: pipeline.nested_cv(d, cfg, timing)) if "cv" in stages else None
    if cv is not None:
        R.csv(cv.selections, "fold_selections")
        R.csv(cv.rule_tables, "inner_rule_grid")
        R.csv(pd.concat([pipeline.forecast_table(t, d, cv.oof) for t in ("price", "spread")]), "forecast_accuracy")
        cal = pd.concat([pipeline.calibration(t, d, cv.oof) for t in ("price", "spread")])
        R.csv(cal, "calibration")
        figures.calibration_figure(cal, R.figs / "calibration.png")
        cv.oof.to_pickle(cache / "oof.pkl")

    tr = None
    if "trading" in stages:
        tr = R.stage("trading", lambda: pipeline.trading(d, cv, cfg, timing), "cv")
        if tr is not None:
            R.csv(tr["summary"], "trading_summary")
            R.csv(tr["bootstrap"], "trading_bootstrap")
            R.json(tr["window_t"], "trading_window_t")
            skill = pd.DataFrame({"model": ["zero", "stock mean", "persistence", "ridge", "HGB"]})
            for t, col in [("spread", "y_spread"), ("price", "y_price")]:
                skill[t] = [pipeline.r2(d.dev_o[col].to_numpy(), cv.oof[f"{t}: {m}"].to_numpy()) for m in skill.model]
            vals = []
            for c in cfg["trading"]["cost_scenarios_bps"]:
                po = pipeline.per_opportunity(tr["ENTER"]["price only"], d.dev_o, c, timing)
                m, lo, hi = pipeline.paired_bootstrap(po, np.zeros(len(po)), d.dev_f.time_id.to_numpy(),
                                                      cfg["bootstrap"]["resamples"], cfg["bootstrap"]["seed"])
                vals.append({"cost_bps": c, "mean_bps": m, "ci_low": lo, "ci_high": hi})
            vals = pd.DataFrame(vals)
            R.csv(skill, "figure1_skill")
            R.csv(vals, "figure1_value")
            note = (f"{label.upper()} run - " if label != "full" else "") + \
                f"Development windows, nested grouped CV; decisions fixed at {cfg['trading']['reference_cost_bps']} bp/side. " \
                "Price + spread policy shown only if it differs (see trading_summary.csv)."
            figures.figure1(skill, vals, R.figs / "figure1_accuracy_vs_value.png", note)

    for name, fn, needs in [
        ("sensitivity", lambda: pipeline.sensitivity(d, cv, tr["ENTER"], cfg, timing), ("trading",)),
        ("why_spread", lambda: pipeline.why_spread(d, cv, tr["ENTER"], cfg, timing), ("trading",)),
        ("ablation", lambda: pipeline.ablation(d, cfg), ()),
        ("leakage", lambda: pipeline.leakage_demo(d, cfg), ()),
    ]:
        if name in stages:
            out = R.stage(name, fn, *needs)
            if isinstance(out, dict):
                for k, v in out.items():
                    R.csv(v, f"{name}_{k}") if isinstance(v, pd.DataFrame) else R.json(v, f"{name}_{k}")
            elif isinstance(out, pd.DataFrame):
                R.csv(out, name)

    if "stress" in stages:
        def stress():
            pts = pd.concat([path_points(s, source.load("book", s), cfg["robustness"]["path_seconds"], timing)
                             for s in stock_ids], ignore_index=True)
            paths = d.dev_f[KEYS].merge(pts, on=KEYS, how="left")
            return pipeline.stress(d, cv, tr["ENTER"], paths, cfg, timing)
        out = R.stage("stress", stress, "trading")
        if out:
            for k, v in out.items():
                R.csv(v, f"stress_{k}") if isinstance(v, pd.DataFrame) else R.json(v, f"stress_{k}")

    up = None
    if "upgraded" in stages:
        if args.skip_upgraded:
            R.skip("upgraded", "--skip-upgraded")
        else:
            up = R.stage("upgraded", lambda: pipeline.upgraded_cv(d, extra, cv, cfg), "cv")
            if up is not None:
                R.csv(up["table"], "upgraded_cv")
                chk = R.stage("upgraded_checks", lambda: pipeline.upgraded_checks(d, up["dev_x"], cfg), "upgraded")
                if chk:
                    R.csv(chk["drivers"], "upgraded_drivers")
                    R.csv(chk["unseen"], "upgraded_unseen_stocks")

    if "benchmark" in stages:
        if not args.score_benchmark:
            R.skip("benchmark", "not requested (pass --score-benchmark to score the legacy benchmark once)")
        else:
            bench = R.stage("benchmark", lambda: pipeline.benchmark_run(d, cfg, timing))
            if bench is not None:
                R.csv(bench["skill"], "benchmark_skill")
                R.csv(bench["trading"], "benchmark_trading")
                R.json(bench["frozen"], "benchmark_frozen_choices")
                if up is not None:
                    ub = R.stage("upgraded_benchmark", lambda: pipeline.upgraded_benchmark(d, extra, bench, cfg),
                                 "upgraded", "benchmark")
                    if ub is not None:
                        R.csv(ub, "upgraded_benchmark")
    R.finish()
    failed = [k for k, v in R.manifest["stages"].items() if v["status"] == "failed"]
    print(f"done ({label}); failed stages: {failed or 'none'}; manifest: {out_dir / 'run_manifest.json'}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
